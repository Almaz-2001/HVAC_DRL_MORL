const byLabel = (lab) => pareto.filter((r) => r.label === lab && r.ms_mean);
const mean = (xs) => xs.reduce((a, b) => a + b, 0) / xs.length;
const std = (xs) => {
  if (xs.length < 2) return 0;
  const m = mean(xs);
  return Math.sqrt(mean(xs.map((x) => (x - m) ** 2)));
};

function paretoRow(lab, name) {
  const rs = byLabel(lab);
  if (!rs.length) return null;
  const e = rs.map((r) => Number(r.energy_kwh_mean));
  const v = rs.map((r) => Number(r.violation_pct_mean));
  const ms = rs.map((r) => Number(r.ms_mean));
  const pm = (a, d) => (rs.length > 1 ? `${a.toFixed(d)} ± ${std(a === mean(e) ? e : a === mean(v) ? v : ms).toFixed(d)}` : a.toFixed(d));
  return [
    name,
    String(rs.length),
    `${mean(e).toFixed(1)}${rs.length > 1 ? " ± " + std(e).toFixed(1) : ""}`,
    `${mean(v).toFixed(1)}${rs.length > 1 ? " ± " + std(v).toFixed(1) : ""}`,
    `${mean(ms).toFixed(3)}${rs.length > 1 ? " ± " + std(ms).toFixed(3) : ""}`,
  ];
}

