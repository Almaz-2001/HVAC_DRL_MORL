# C1 — Pipeline schematic
# ---------------------------------------------------------------------------


def _pipeline_box(ax, x, y, w, h, title, body, color, body_color=None):
    body_color = body_color or "#ffffff"
    box = FancyBboxPatch(
        (x, y),
        w,
        h,
        boxstyle="round,pad=0.02,rounding_size=0.04",
        linewidth=1.4,
        edgecolor=color,
        facecolor=body_color,
        zorder=2,
    )
    ax.add_patch(box)
    ax.text(
        x + w / 2,
        y + h - 0.06,
        title,
        ha="center",
        va="top",
        fontsize=10,
        fontweight="bold",
        color=color,
        zorder=3,
    )
    ax.text(
        x + w / 2,
        y + h / 2 - 0.05,
        body,
        ha="center",
        va="center",
        fontsize=8.5,
        color=PALETTE["ink"],
        zorder=3,
    )


def _pipeline_arrow(ax, x1, x2, y, color=None):
    color = color or PALETTE["muted"]
    ax.annotate(
        "",
        xy=(x2, y),
        xytext=(x1, y),
        arrowprops=dict(arrowstyle="-|>", color=color, lw=1.6, shrinkA=2, shrinkB=2),
        zorder=4,
    )


def build_pipeline_schematic() -> None:
    fig, ax = plt.subplots(figsize=(11.0, 4.2))
    ax.set_xlim(0, 11)
    ax.set_ylim(0, 4.2)
    ax.set_axis_off()

    # Five primary boxes along the row
    boxes = [
        dict(
            x=0.15,
            title="Data",
            body=(
                "BOPTEST bestest_air\n"
                "~200k transitions\n"
                "15-min step, TMY"
            ),
            color=PALETTE["blue"],
        ),
        dict(
            x=2.35,
            title="Calibration",
            body=(
                "Stage A — preprocess\n"
                "Stage B — identify Czon\n"
                "Stage C — residual fit"
            ),
            color=PALETTE["success"],
        ),
        dict(
            x=4.55,
            title="Hybrid backend",
            body=(
                "v3 = fast training env\n"
                "v3.5 = frozen anchor\n"
                "1787 steps/s (85x)"
            ),
            color=PALETTE["accent"],
        ),
        dict(
            x=6.75,
            title="Controllers",
            body=(
                "Thermostatic PPO\n"
                "HDRL hierarchical\n"
                "17-D MORL preference"
            ),
            color=PALETTE["warn"],
        ),
        dict(
            x=8.95,
            title="Live BOPTEST",
            body=(
                "Frozen policy\n"
                "Peak / typical / yearly\n"
                "ms, energy, RMSE_T"
            ),
            color=PALETTE["ink"],
        ),
    ]

    w, h = 2.0, 2.1
    y_box = 1.5
    centres = []
    for b in boxes:
        _pipeline_box(ax, b["x"], y_box, w, h, b["title"], b["body"], b["color"])
        centres.append(b["x"] + w / 2)

    # Arrows between boxes
    y_arrow = y_box + h / 2
    for i in range(len(boxes) - 1):
        x1 = boxes[i]["x"] + w + 0.05
        x2 = boxes[i + 1]["x"] - 0.05
        _pipeline_arrow(ax, x1, x2, y_arrow)

    # Lambda anchor overlay (v3.5 enters the loss, not the rollout)
    anchor_y = 0.45
    anchor_box = FancyBboxPatch(
        (3.5, anchor_y - 0.05),
        4.5,
        0.55,
        boxstyle="round,pad=0.02,rounding_size=0.05",
        linewidth=1.2,
        edgecolor=PALETTE["accent"],
        facecolor="#fff7e6",
        linestyle="--",
        zorder=2,
    )
    ax.add_patch(anchor_box)
    ax.text(
        3.5 + 4.5 / 2,
        anchor_y + 0.22,
        "Hybrid loss:  L_PPO  +  lambda_temp x (T_v3 - T_v3.5)^2  +  lambda_power x (P_v3 - P_v3.5)^2",
        ha="center",
        va="center",
        fontsize=9,
        color=PALETTE["ink"],
    )

    # Vertical arrow from the Calibration box to the anchor
    ax.annotate(
        "",
        xy=(5.55, anchor_y + 0.5),
        xytext=(5.55, y_box),
        arrowprops=dict(
            arrowstyle="-|>",
            color=PALETTE["accent"],
            lw=1.4,
            linestyle="--",
            shrinkA=2,
            shrinkB=2,
        ),
        zorder=4,
    )

    # Title
    ax.text(
        5.5,
        3.95,
        "Hybrid surrogate pipeline (Block 1 + Block 2)",
        ha="center",
        va="top",
        fontsize=12,
        fontweight="bold",
        color=PALETTE["ink"],
    )

    # Footer caption notes
    ax.text(
        5.5,
        0.15,
        "v3.5 is frozen after Stage A/B/C — enters only the disagreement penalty, never the rollout forward pass.",
        ha="center",
        va="center",
        fontsize=8.5,
        style="italic",
        color=PALETTE["muted"],
    )

    _save(fig, "C1_pipeline_overview")


