def build_component_decomposition() -> None:
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(11.0, 4.4))
    fig.subplots_adjust(wspace=0.30)

    # Panel (a): surrogate-side RMSE_T improvement under full Stage A/B/C
    testcases = [
        "bestest_hydronic\nheat_pump",
        "bestest_hydronic",
        "singlezone_commercial\nhydronic",
    ]
    rmse_before = np.array([1.421, 2.666, 1.952])
    rmse_after = np.array([0.565, 0.335, 0.238])
    improvement_pct = (1.0 - rmse_after / rmse_before) * 100.0

    x = np.arange(len(testcases))
    width = 0.36
    ax1.bar(
        x - width / 2,
        rmse_before,
        width,
        label="before recalibration",
        color=PALETTE["warn"],
        edgecolor=PALETTE["ink"],
        linewidth=0.9,
    )
    ax1.bar(
        x + width / 2,
        rmse_after,
        width,
        label="after full Stage A/B/C",
        color=PALETTE["success"],
        edgecolor=PALETTE["ink"],
        linewidth=0.9,
    )

    for xi, b, a, imp in zip(x, rmse_before, rmse_after, improvement_pct):
        ax1.text(
            xi,
            max(b, a) + 0.15,
            f"-{imp:.1f}%",
            ha="center",
            va="bottom",
            fontsize=9,
            color=PALETTE["ink"],
            fontweight="bold",
        )
    ax1.set_xticks(x)
    ax1.set_xticklabels(testcases, fontsize=8.5)
    ax1.set_ylabel("temperature RMSE  (deg C)")
    ax1.set_title("(a) Surrogate-side: 3/3 PASS under full Stage A/B/C", loc="left")
    ax1.legend(loc="upper right", frameon=False)
    ax1.set_ylim(0, max(rmse_before) * 1.25)
    ax1.grid(axis="y", alpha=0.25)

    # Panel (b): controller verdict matrix
    verdicts = np.array(
        [
            # rows = testcases, cols = regimes (none, partial, full)
            [0, 0, 0],  # heat_pump        FAIL FAIL FAIL
            [0, 0, 0],  # hydronic         FAIL FAIL FAIL
            [1, 1, 1],  # commercial       THRESHOLD PASS but deployment FAIL
        ]
    )
    # Encode 0=FAIL, 1=THRESHOLD-PASS-only, 2=DEPLOYMENT-PASS (none in Block3)
    color_map = {0: PALETTE["warn"], 1: PALETTE["accent"], 2: PALETTE["success"]}
    label_map = {0: "FAIL\n(deployment)", 1: "THRESHOLD\nPASS only", 2: "DEPLOYMENT\nPASS"}

    ax2.set_xlim(-0.5, 2.5)
    ax2.set_ylim(-0.5, 2.5)
    ax2.set_xticks([0, 1, 2])
    ax2.set_xticklabels(["none", "partial\nStage C", "full\nStage A/B/C"])
    ax2.set_yticks([0, 1, 2])
    ax2.set_yticklabels(
        [
            "singlezone_commercial",
            "bestest_hydronic",
            "bestest_hydronic_heat_pump",
        ]
    )
    # Note: rows top-down; invert to match conventional matrix top-row first
    for i in range(verdicts.shape[0]):
        for j in range(verdicts.shape[1]):
            v = verdicts[verdicts.shape[0] - 1 - i, j]  # invert vertical
            cell = Rectangle(
                (j - 0.45, i - 0.45),
                0.9,
                0.9,
                facecolor=color_map[v],
                edgecolor=PALETTE["ink"],
                linewidth=0.9,
                alpha=0.85,
            )
            ax2.add_patch(cell)
            ax2.text(
                j,
                i,
                label_map[v],
                ha="center",
                va="center",
                fontsize=8.5,
                color="white" if v == 0 else PALETTE["ink"],
                fontweight="bold",
            )
    ax2.set_title(
        "(b) Controller-side: 0/9 deployment-PASS\n"
        "(frozen direct-TSup policy; mechanical hydronic adapter)",
        loc="left",
        fontsize=10,
    )
    ax2.invert_yaxis()
    ax2.spines["top"].set_visible(True)
    ax2.spines["right"].set_visible(True)
    ax2.tick_params(left=False, bottom=False)

    fig.suptitle(
        "Component decomposition of transferability:  surrogate transfers structurally  /  controller does not",
        fontsize=11.5,
        fontweight="bold",
        color=PALETTE["ink"],
        y=1.02,
    )
    _save(fig, "C3_component_decomposition")


