"""
Conceptual figures for the paper that are NOT autogenerated from CSV
metrics. These are diagrammatic / synthesizing figures: pipeline
overview, C_zon cross-testcase consistency, and Block 3 component
decomposition.

  C1  pipeline_overview              — data → calibration → hybrid
                                       backend → controllers → live
                                       BOPTEST (Methods)
  C2  czon_consistency               — bar chart of C_zon across
                                       bestest_air + 3 hydronic
                                       testcases (Results III)
  C3  component_decomposition        — 2-panel diagnostic of
                                       surrogate-side vs controller-side
                                       transfer outcomes (Results III)

All three are written as PDF (paper) and PNG (slides) into
paper/figures/q1/, alongside the Q1–Q10 autogenerated suite.
"""

from __future__ import annotations

import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from matplotlib.patches import FancyArrow, FancyBboxPatch, Rectangle

PAPER_DIR = Path(__file__).resolve().parent
OUT_DIR = PAPER_DIR / "figures" / "q1"
OUT_DIR.mkdir(parents=True, exist_ok=True)

PALETTE = {
    "ink": "#1a1a2e",
    "muted": "#9a9a9a",
    "warn": "#c1121f",
    "success": "#0f8a5f",
    "accent": "#f4a261",
    "blue": "#1e6091",
    "light_bg": "#f5f3ee",
    "panel_bg": "#ffffff",
}

plt.rcParams.update(
    {
        "font.family": "DejaVu Sans",
        "font.size": 10,
        "axes.titlesize": 11,
        "axes.labelsize": 10,
        "xtick.labelsize": 9,
        "ytick.labelsize": 9,
        "legend.fontsize": 9,
        "axes.spines.top": False,
        "axes.spines.right": False,
        "savefig.dpi": 300,
        "savefig.bbox": "tight",
    }
)


def _save(fig, name: str) -> None:
    for ext in ("pdf", "png"):
        path = OUT_DIR / f"{name}.{ext}"
        fig.savefig(path)
    plt.close(fig)
    print(f"[OK] wrote {OUT_DIR / name}.pdf + .png")


